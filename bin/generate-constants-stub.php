#!/usr/bin/env php
<?php

declare(strict_types=1);

use App\Config\ConfigLoader;

$baseDir = dirname(__DIR__);

require $baseDir . '/vendor/autoload.php';
// Evita carregamento de configurações vindas do banco durante a geração.
putenv('DISABLE_DB_ON_BOOT=1');
$_ENV['DISABLE_DB_ON_BOOT'] = '1';

ConfigLoader::boot();

$userConstants = get_defined_constants(true)['user'] ?? [];
if ([] === $userConstants) {
    fwrite(STDERR, "Nenhuma constante de usuário encontrada.\n");

    exit(1);
}

ksort($userConstants);

$lines = [];
$lines[] = '<?php';
$lines[] = '';
$lines[] = 'declare(strict_types=1);';
$lines[] = '';
$lines[] = '// @generated by bin/generate-constants-stub.php';
$lines[] = '// phpcs:ignoreFile -- Arquivo auxiliar para autocompletar constantes no IDE.';
$lines[] = '';

foreach ($userConstants as $name => $value) {
    if (!is_string($name) || '' === $name) {
        continue;
    }

    if (is_bool($value)) {
        $export = $value ? 'true' : 'false';
    } elseif (is_int($value) || is_float($value)) {
        $export = (string)$value;
    } else {
        $export = var_export((string)$value, true);
    }

    $lines[] = sprintf("if (!defined('%s')) {", $name);
    $lines[] = sprintf("    define('%s', %s);", $name, $export);
    $lines[] = '}';
    $lines[] = '';
}

$stubPath = $baseDir . '/_app/Config/constants_stub.php';
file_put_contents($stubPath, implode(PHP_EOL, $lines));

fwrite(STDOUT, sprintf("Stub gerado em %s\n", $stubPath));
